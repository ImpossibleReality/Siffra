//! The signed over-the-air update integration.
//!
//! Release automation supplies `SIFFRA_UPDATER_PUBLIC_KEY` while compiling a
//! distributable build. Local builds deliberately leave it unset, which makes
//! update checks a no-op instead of requiring a private release credential.

use cargo_packager_updater::{Config, Error, Update, check_update, semver::Version, url::Url};

/// The stable GitHub Release asset that describes the newest signed update.
pub const ENDPOINT: &str =
    "https://github.com/ImpossibleReality/Siffra/releases/latest/download/latest.json";

/// Checks GitHub Releases for a newer, signed package.
///
/// `Update::body` contains the release notes generated by `git-cliff`; callers
/// should show those notes before invoking [`install`]. A local development
/// build has no embedded release public key and therefore returns `Ok(None)`.
pub fn check() -> Result<Option<Update>, Error> {
    let Some(public_key) = option_env!("SIFFRA_UPDATER_PUBLIC_KEY").filter(|key| !key.is_empty())
    else {
        return Ok(None);
    };

    let config = Config {
        endpoints: vec![Url::parse(ENDPOINT).expect("the built-in update endpoint is valid")],
        pubkey: public_key.into(),
        ..Default::default()
    };
    let version = Version::parse(env!("CARGO_PKG_VERSION"))
        .expect("the package version is valid semantic versioning");

    check_update(version, config)
}

/// Installs an update after the UI has shown its version and release notes.
pub fn install(update: &Update) -> Result<(), Error> {
    update.download_and_install()
}

/// A short, single-line summary suitable for the existing status toast.
pub fn summary(update: &Update) -> String {
    let notes = update
        .body
        .as_deref()
        .unwrap_or("No release notes were provided.")
        .split_whitespace()
        .take(12)
        .collect::<Vec<_>>()
        .join(" ");
    format!("Siffra {} is ready: {notes}", update.version)
}
